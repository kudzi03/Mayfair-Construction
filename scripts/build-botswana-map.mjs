// Generates src/content/botswana-map.ts from a GeoJSON Polygon of Botswana.
// Source used for the demo: Natural Earth 1:50m admin-0 countries (public domain).
// Usage: node scripts/build-botswana-map.mjs path/to/botswana-geometry.json
import { readFileSync, writeFileSync } from "node:fs";

const [, , input] = process.argv;
if (!input) throw new Error("Pass a GeoJSON geometry file for Botswana");

const geometry = JSON.parse(readFileSync(input, "utf8"));
const ring = geometry.type === "Polygon" ? geometry.coordinates[0] : geometry.coordinates[0][0];

const lons = ring.map(([lon]) => lon);
const lats = ring.map(([, lat]) => lat);
const bounds = {
  minLon: Math.min(...lons),
  maxLon: Math.max(...lons),
  minLat: Math.min(...lats),
  maxLat: Math.max(...lats),
};
// Equirectangular projection corrected for Botswana's mid latitude.
const kx = Math.cos((((bounds.minLat + bounds.maxLat) / 2) * Math.PI) / 180);
const width = 1000;
const scale = width / ((bounds.maxLon - bounds.minLon) * kx);
const height = Math.round((bounds.maxLat - bounds.minLat) * scale);
const pad = 40;

const round = (n) => Math.round(n * 10) / 10;
const pts = ring.map(([lon, lat]) => [
  round((lon - bounds.minLon) * kx * scale + pad),
  round((bounds.maxLat - lat) * scale + pad),
]);
const path = "M" + pts.map(([x, y]) => `${x} ${y}`).join("L") + "Z";

const out = `// Generated by scripts/build-botswana-map.mjs — do not edit by hand.
// Outline: Natural Earth 1:50m admin-0 countries (public domain).

export const botswanaMap = {
  viewBox: { width: ${width + pad * 2}, height: ${height + pad * 2} },
  projection: {
    minLon: ${bounds.minLon},
    maxLat: ${bounds.maxLat},
    kx: ${kx},
    scale: ${scale},
    pad: ${pad},
  },
  outline: "${path}",
} as const;
`;
writeFileSync(new URL("../src/content/botswana-map.ts", import.meta.url), out);
console.log(`Wrote outline with ${pts.length} points, viewBox ${width + pad * 2}x${height + pad * 2}`);
